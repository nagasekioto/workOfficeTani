/*
 * 駅名から路線を引く。
 * 戻り値は { key: 実際に一致した駅名, lines: [路線...] }、見つからなければ null。
 *
 * 入力途中でも拾えるように部分一致も見るが、1文字だけの部分一致は
 * 「田」で三田・田町・田端…と無関係な駅を引いてしまうため行わない。
 */
function findStationLines(stationName) {
    var name = (stationName || '').trim().replace(/駅$/, '');
    if (!name) return null;

    if (STATION_LINES[name]) return { key: name, lines: STATION_LINES[name] };
    if (name.length < 2) return null;

    var key = Object.keys(STATION_LINES).find(function (k) {
        return k.indexOf(name) !== -1 || name.indexOf(k) !== -1;
    });
    return key ? { key: key, lines: STATION_LINES[key] } : null;
}
